export const getProduct = (id) => products.find((p) => p.id === id)

export const featuredProducts = products.filter((p) =>
  ['ef-delta-2-max', 'rad-power-rover', 'macbook-air-m3', 'samsung-tv-65', 'segway-max-g2', 'starlink-mini'].includes(p.id),
)

// Más vendidos — ordenados por número de reseñas
export const bestSellers = [...products].sort((a, b) => b.reviews - a.reviews).slice(0, 5)

// Ofertas — productos con precio rebajado, mayor descuento primero
export const offers = products
  .filter((p) => p.compareAt && p.stock > 0)
  .sort((a, b) => 1 - a.price / a.compareAt - (1 - b.price / b.compareAt))
  .reverse()
  .slice(0, 5)

// Recomendados — mejor valorados
export const recommended = [...products].sort((a, b) => b.rating - a.rating).slice(0, 5)

// Recientemente agregados — los marcados como "Nuevo" + más recientes del array
export const recentlyAdded = [
  ...products.filter((p) => p.badge === 'Nuevo'),
  ...products.filter((p) => p.badge !== 'Nuevo'),
].slice(0, 5)

export const discountPct = (p) => (p.compareAt ? Math.round((1 - p.price / p.compareAt) * 100) : 0)
